'use strict';
const assert=require('node:assert/strict');
const C=require('../assets/budget-range-core.js');
const params={people:2,days:2,nights:1,rooms:1,paidActivities:2,bands:C.defaults.balanced,km:120,efficiency:12,fuelPrice:23.68,tolls:0};
const x=C.compute(params);
assert.equal(x.fuel,236.8);
assert.equal(x.low,700+880+400+236.8);
assert.equal(x.high,1600+2000+2000+236.8);
assert.equal(x.missing.includes('road distance / fuel'),false);
assert.equal(C.compute({...params,km:null}).fuel,null);
assert.equal(C.compute({...params,paidActivities:2,pricedActivities:1}).unknownActivityCount,1);
const quoted=C.compute({...params,published:180,pricedActivities:1,lodgingIncluded:true});
assert.equal(quoted.assumed.room[1],0);
assert.equal(quoted.published,180);
assert.ok(quoted.high>quoted.low);
assert.throws(()=>C.compute({...params,bands:{...C.defaults.balanced,room:[2000,300]}}),/Invalid assumption/);
assert.equal(C.compute({...params,paidActivities:0}).assumed.activity[1],0);
assert.equal(C.compute({...params,tolls:null}).missing.includes('tolls'),true);
console.log('PASS: 10 key spending-envelope assertions');
