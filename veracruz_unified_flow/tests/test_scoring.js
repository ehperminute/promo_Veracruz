'use strict';
const assert=require('node:assert/strict');
const S=require('../assets/discovery-scoring.js');
const row=(city,feature,group,proof=true)=>({municipality_id:city,feature_id:feature,family:group,original_text_support:proof,source_urls:proof?['https://example.org/evidence']:[]});
const rows=[row('A','museum','culture'),row('B','museum','culture'),row('C','museum','culture'),row('D','museum','culture'),row('B','paper_balloon_workshop','crafts'),row('C','raft','water',false)];
const freq=S.frequency(rows);
assert.equal(freq.get('museum'),4);
assert.equal(freq.get('paper_balloon_workshop'),1);
assert.equal(S.credible(rows[5]),false);
assert.equal(S.autoSuitable(row('X','ceremony_honoring_mother_earth','culture')),false);
assert.equal(S.autoSuitable(row('X','paper_balloon_workshop','crafts')),true);
assert.ok(S.rarity(rows[4],freq)>S.rarity(rows[0],freq));
const b={id:'B',rows:rows.filter(x=>x.municipality_id==='B')};
const c={id:'C',rows:rows.filter(x=>x.municipality_id==='C')};
assert.ok(S.candidate(b,freq)>S.candidate(c,freq),'Rare documented craft outranks only common museum');
assert.equal(S.candidate({id:'D',rows:[row('D','x','crafts',false)]},freq),-Infinity,'No documented original/source proof means no surprise');
assert.equal(S.portfolio([b],freq,20,()=>0.5)>-Infinity,true);
assert.equal(S.portfolio([{id:'D',rows:[row('D','x','crafts',false)]}],freq,20,()=>0.5),-Infinity);
assert.equal(S.reasons(b,freq)[0].feature_id,'paper_balloon_workshop');
console.log('PASS: five novelty, evidence, diversity and no-false-popularity checks.');
